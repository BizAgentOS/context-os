import { createFusionSources, primaryCapability, supplementCapability, fusionDefinition } from "./fusion-fixture.ts";

const ref = (a: { id: string; version: number }) => ({ id: a.id, version: a.version });
const definition = { enterprise: { name: "Release fixture" }, concepts: [{ id: "company", name: "公司", description: "接受服务的公司" }], relations: [], evidence: [], unknowns: [], conflicts: [] };

test("release lifecycle is checked, immutable, idempotent, scoped, and survives restart", async () => {
  const directory = mkdtempSync(join(tmpdir(), "ade-releases-"));
  let memory = new MemoryStore(directory);
  let live = new LiveMemory(directory, memory);
  let releases = new Releases(memory, live);
  try {
    assert.equal(releases.overview().currentRelease, null);
    const empty = await releases.check({ inputHash: releases.overview().working.inputHash });
    assert.equal(empty.status, "blocked");
    assert.throws(() => releases.publish({ operationId: "empty", checkRef: ref(empty), name: "v1" }), /检查|发布/);
    const f = memory.putArtifact({ kind: "foundation", title: "公司本体", status: "adopted", content: definition });
    const checked = await releases.check({ inputHash: releases.overview().working.inputHash });
    assert.equal(checked.status, "ready");
    const input = { operationId: "first", checkRef: ref(checked), name: "v1.0", notes: "首个定义版本" };
    const first = releases.publish(input);
    assert.equal(first.release.content.sequence, 1);
    assert.equal(releases.publish(input).release.id, first.release.id);
    assert.throws(() => releases.publish({ ...input, name: "different" }), /幂等|操作标识/);
    assert.throws(() => releases.publish({ ...input, operationId: "concurrent-publisher", name: "v1.1" }), /变化|检查/);
    const selection = { operationId: "consumer", name: "Agent A", releaseRef: ref(first.release), conceptIds: ["company"], relationIds: [], agentEnabled: true };
    const consumer = releases.connect(selection);
    assert.equal(consumer.connection.content.agentEnabled, true);
    assert.match(consumer.key!, /^de_dataset_/);
    assert.equal(releases.connect(selection).key, null);
    assert.doesNotMatch(JSON.stringify(releases.overview()), /keyHash|de_dataset_/);
    const datasets = new OntologyDatasets(memory, live);
    const read = () => datasets.handle("/v4/concept", new URLSearchParams({ conceptId: "company" }), "Bearer " + consumer.key);
    assert.equal((await read()).status, 200);
    memory.putArtifact({ ...f, expectedVersion: f.version, status: "candidate", content: { ...definition, adoptedVersion: f.version, concepts: [{ id: "company", name: "公司", description: "未采纳修改" }] } });
    assert.equal(releases.overview().working.pending.length, 1);
    assert.equal((await read()).body.concept && ((await read()).body.concept as any).description, "接受服务的公司");
    // Confirmed 2026-10-19 (FEATURE_041): pending work warns but no longer blocks, and it is not part of the release.
    const unblocked = await releases.check({ inputHash: releases.overview().working.inputHash });
    assert.equal(unblocked.status, "ready");
    const pendingIssue = (unblocked.content.issues as any[]).find(issue => issue.code === "pending_changes");
    assert.equal(pendingIssue.severity, "warning");
    assert.deepEqual((unblocked.content.definition as any).concepts, [{ id: "company", name: "公司", description: "接受服务的公司" }], "the unadopted wording is not in the release");
    assert.equal(releases.read(ref(first.release)).content.name, "v1.0");
    memory.close();
    memory = new MemoryStore(directory); live = new LiveMemory(directory, memory); releases = new Releases(memory, live);
    assert.equal(releases.overview().connections.length, 1);
    const spec = releases.connection(ref(consumer.connection), "http://localhost:9999");
    assert.ok(spec.mcp.mcpServers);
    releases.revoke({ operationId: "revoke", connectionRef: ref(consumer.connection) });
    assert.equal((await new OntologyDatasets(memory, live).handle("/v4/dataset", new URLSearchParams(), "Bearer " + consumer.key)).status, 403);
  } finally { memory.close(); rmSync(directory, { recursive: true, force: true }); }
});

test("published business versions remain independent over source updates, explicit upgrades preserve grants, and stale checks fail", async () => {
  const directory = mkdtempSync(join(tmpdir(), "ade-release-business-"));
  const source = await createFusionSources();
  const memory = new MemoryStore(directory), live = new LiveMemory(directory, memory);
  const releases = new Releases(memory, live), datasets = new OntologyDatasets(memory, live);
  const server = createHttpServer(async (req, res) => {
    const url = new URL(req.url!, "http://localhost");
    const result = await datasets.handle(url.pathname, url.searchParams, req.headers.authorization);
    res.writeHead(result.status, { "content-type": "application/json" }); res.end(JSON.stringify(result.body));
  });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const read = async (key: string, path = "/v4/objects?type=" + encodeURIComponent("投诉") + "&limit=1") => {
    const response = await fetch(origin + path, { headers: { authorization: "Bearer " + key } });
    return { status: response.status, body: await response.json() as any };
  };
  let unblock: (() => void) | undefined;
  try {
    const f = memory.putArtifact({ kind: "foundation", title: "服务本体", status: "adopted", content: { ...definition, concepts: [{ id: "complaint", name: "投诉", description: "居民投诉" }] } });
    const primary = await live.sources.connect({ name: "primary", protocol: "http", url: source.url, capabilities: [primaryCapability] });
    const supplement = await live.sources.connect({ name: "workorders", protocol: "mcp", url: source.url + "/mcp", capabilities: [supplementCapability] });
    const base = fusionDefinition(primary.id, supplement.id);
    const initial = { ...base, foundationRef: ref(f), baseModelRef: null, types: base.types.map(t => ({ ...t, conceptId: "complaint" })) };
    const draft = await live.propose(initial), model = await live.adopt(draft.id, draft.version);
    const check = await releases.check({ inputHash: releases.overview().working.inputHash });
    assert.equal(check.status, "ready");
    const first = releases.publish({ operationId: "pub1", checkRef: ref(check), name: "v1" }).release;
    const grants = [{ type: "投诉", fields: ["$id", "状态", "实际反馈"], relations: [], evidence: { fields: ["状态"], relations: [] } }];
    const a = releases.connect({ operationId: "a", name: "A", releaseRef: ref(first), conceptIds: ["complaint"], relationIds: [], business: { grants } });
    const b = releases.connect({ operationId: "b", name: "B", releaseRef: ref(first), conceptIds: ["complaint"], relationIds: [], business: { grants: [{ type: "投诉", fields: ["$id", "实际反馈"], relations: [] }] } });
    const initialRead = await read(a.key!);
    assert.equal(initialRead.status, 200);
    assert.equal(initialRead.body.items[0].properties.实际反馈.value, "未改善");
    const stale = await releases.check({ inputHash: releases.overview().working.inputHash });
    const f2 = memory.putArtifact({ ...f, expectedVersion: f.version, content: { ...f.content, concepts: [{ id: "complaint", name: "投诉", description: "已登记居民投诉" }, { id: "new", name: "新增概念", description: "尚未对外授权" }] } });
    assert.throws(() => releases.publish({ operationId: "stale", checkRef: ref(stale), name: "stale" }), /变化|检查/);
    source.state.mode = "conflict";
    const pinned = await read(a.key!);
    assert.equal(pinned.status, 200, "adopting a newer foundation must not invalidate published semantic definitions");
    assert.equal(pinned.body.items[0].properties.状态.status, "conflict", "facts still come from current source reads");
    assert.equal((await read(a.key!, "/v4/concept?conceptId=complaint")).body.concept.description, "居民投诉");
    const next = { ...initial, foundationRef: ref(f2), baseModelRef: ref(model), types: initial.types.map(t => ({ ...t, description: "已登记居民投诉", fields: { ...t.fields, 电话: "phone" } })) };
    const nextDraft = await live.propose(next); const nextModel = await live.adopt(nextDraft.id, nextDraft.version);
    const working = releases.overview().working;
    assert.ok(working.diff.some(d => d.path === "/concepts/complaint/description" && d.before === "居民投诉" && d.after === "已登记居民投诉"));
    const check2 = await releases.check({ inputHash: working.inputHash });
    source.state.mode = "failure";
    const unavailable = await releases.check({ inputHash: working.inputHash });
    assert.equal(unavailable.status, "blocked", "a failed supplementary source must fail a new release check");
    assert.ok((unavailable.content.issues as any[]).some(i => i.code === "source_check_failed"));
    assert.throws(() => releases.publish({ operationId: "unavailable", checkRef: ref(unavailable), name: "bad" }), /检查/);
    source.state.mode = "conflict";
    assert.throws(() => releases.publish({ operationId: "old-check", checkRef: ref(check2), name: "bad" }), /最新|检查/);
    const finalCheck = await releases.check({ inputHash: working.inputHash });
    const second = releases.publish({ operationId: "pub2", checkRef: ref(finalCheck), name: "v2" }).release;
    assert.equal((await read(a.key!)).status, 200);
    const upgraded = releases.upgrade({ operationId: "upgrade", connectionRef: ref(a.connection), releaseRef: ref(second) });
    assert.equal(upgraded.connection.version, 2);
    assert.deepEqual((upgraded.connection.content.business as any).grants, grants);
    assert.equal((await read(a.key!)).status, 403);
    assert.equal((await read(b.key!)).status, 200, "another consumer remains on its own published version");
    assert.equal((await read(upgraded.key!, "/v4/concept?conceptId=complaint")).body.concept.description, "已登记居民投诉");
    assert.equal((await read(upgraded.key!, "/v4/concept?conceptId=new")).status, 403);
    assert.equal((await read(upgraded.key!, "/v4/objects?type=" + encodeURIComponent("投诉") + "&fields=" + encodeURIComponent("$id,电话"))).status, 403);
    assert.equal(releases.upgrade({ operationId: "upgrade", connectionRef: ref(a.connection), releaseRef: ref(second) }).key, null);
    assert.equal((await read(upgraded.key!, "/v4/evidence?ref=" + initialRead.body.items[0].properties.状态.evidenceRef)).status, 403);
    const calls = source.state.calls;
    source.state.delay = new Promise<void>(resolve => { unblock = resolve; });
    const inFlight = read(upgraded.key!);
    const deadline = Date.now() + 5000;
    while (source.state.calls === calls && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 5));
    assert.ok(source.state.calls > calls);
    releases.revoke({ operationId: "stop", connectionRef: ref(upgraded.connection) });
    unblock!();
    assert.equal((await inFlight).status, 403);
    const incompatible = { ...next, baseModelRef: ref(nextModel), types: next.types.map(t => ({ ...t, supplements: t.supplements.map(s => ({ ...s, fields: { 状态: "status", 上门次数: "visits" } })) })) };
    const incompatibleDraft = await live.propose(incompatible); await live.adopt(incompatibleDraft.id, incompatibleDraft.version);
    const check3 = await releases.check({ inputHash: releases.overview().working.inputHash });
    const third = releases.publish({ operationId: "pub3", checkRef: ref(check3), name: "v3" }).release;
    assert.throws(() => releases.upgrade({ operationId: "incompatible", connectionRef: ref(b.connection), releaseRef: ref(third) }), /字段|授权/);
    assert.equal((await read(b.key!)).status, 200, "an incompatible upgrade must not revoke a working old connection");
    assert.equal(releases.overview().connections.find(c => c.id === b.connection.id)!.version, 1);
    live.sources.disable(primary.id, primary.version);
    assert.equal((await read(b.key!)).status, 502, "fixed semantics do not retain revoked source access");
    const disabled = await releases.check({ inputHash: releases.overview().working.inputHash });
    assert.equal(disabled.status, "blocked");
  } finally {
    unblock?.(); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve()));
    await source.close(); memory.close(); rmSync(directory, { recursive: true, force: true });
  }
});
